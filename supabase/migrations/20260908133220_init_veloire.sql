create or replace function vlr_private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.vlr_profiles (id, email, full_name, avatar_url, role)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name'),
    new.raw_user_meta_data ->> 'avatar_url',
    case when lower(coalesce(new.email, '')) = 'lia.thedev@gmail.com' then 'admin' else 'customer' end
  )
  on conflict (id) do update set
    email = excluded.email,
    full_name = coalesce(public.vlr_profiles.full_name, excluded.full_name),
    avatar_url = coalesce(public.vlr_profiles.avatar_url, excluded.avatar_url),
    role = case when lower(excluded.email) = 'lia.thedev@gmail.com' then 'admin' else public.vlr_profiles.role end;
  return new;
end;
$$;
revoke all on function vlr_private.handle_new_user() from public, anon, authenticated;

