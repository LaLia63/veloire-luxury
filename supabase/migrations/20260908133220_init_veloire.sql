create or replace function vlr_private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.vlr_profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;
revoke all on function vlr_private.is_admin() from public;
grant usage on schema vlr_private to authenticated;
grant execute on function vlr_private.is_admin() to authenticated;

